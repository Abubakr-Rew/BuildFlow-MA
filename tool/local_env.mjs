// Writes env/local.env for running the app against the local Supabase:
//
//   node tool/local_env.mjs
//   flutter run --dart-define-from-file=env/local.env
//
// The stack must be running (npx supabase@2.122.0 start). The URL is
// 127.0.0.1: on a phone over USB it reaches the computer through
// `adb reverse tcp:54321 tcp:54321` (README). env/*.env is not in git.
import { execSync } from 'node:child_process';
import { mkdirSync, writeFileSync } from 'node:fs';

let status;
try {
  status = JSON.parse(
    execSync('npx supabase@2.122.0 status -o json', { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }),
  );
} catch {
  console.error('Supabase is not running: start it with `npx supabase@2.122.0 start`.');
  process.exit(1);
}

const url = new URL(status.API_URL);
const key = status.ANON_KEY;
if (!key) {
  console.error('`supabase status` printed no ANON_KEY.');
  process.exit(1);
}

mkdirSync('env', { recursive: true });
writeFileSync(
  'env/local.env',
  [
    '# Generated by tool/local_env.mjs; not in git.',
    'BACKEND=supabase',
    `SUPABASE_URL=http://127.0.0.1:${url.port}`,
    `SUPABASE_ANON_KEY=${key}`,
    '',
  ].join('\n'),
);
console.log(`env/local.env: SUPABASE_URL=http://127.0.0.1:${url.port}`);
